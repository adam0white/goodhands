test('fresh local and canonical starts pin plain narration and replay current exports', async () => {
  expect(freshCast('nermin', 7, 510).lexicon?.plainEnglish).toBe(true);
  expect(freshGuest('selin-voice').person.lexicon?.plainEnglish).toBe(true);
  const state = newGame(7);
  expect(Object.values(state.people).every((p) => p.lexicon?.plainEnglish === true)).toBe(true);
  apply(state, { type: 'pause-cast' });
  const transfer = await agencyTransfer(state, 'nermin');
  const parent = await createPersona({
    format: 'hf-persona/1',
    castId: CAST.nermin.castId,
    castRevision: CAST.nermin.revision,
    branchId: 'upgrade-test',
    parentRevision: null,
    source: { game: 'goodhands', build: 'test', engine: '2.23.0', rules: 'goodhands-6' },
    transfer: { ...transfer, life: initialPersonaLife(CAST.nermin.castId, 'upgrade-test', 0) },
    limitations: [],
  });
  const { revision: _revision, ...body } = parent;
  const future = await createPersona({ ...body, source: { ...body.source, engine: '2.22.0' } });
  await expect(prepareAgencyChapter([preparePersonaLife(future, 0)], 7)).rejects.toThrow(/cannot continue/);
  const wrongRole = await createPersona({
    ...body,
    transfer: { ...body.transfer, sourceRole: 'hatice' },
  });
  await expect(prepareAgencyChapter([preparePersonaLife(wrongRole, 0)], 7)).rejects.toThrow(
    /cannot continue/,
  );
  const chapter = await prepareAgencyChapter([preparePersonaLife(parent, 0)], 7);
  const current = newGame(7, 6, chapter.guests, chapter);
  expect(current.people.nermin?.lexicon?.plainEnglish).toBe(true);
  advance(current, 60);
  expect(fingerprint(replay(7, current.inputs, current.now, 6, chapter.guests, chapter))).toBe(
    fingerprint(current),
  );
  const continuity = emptyContinuity();
  continuity.chapter = chapter;
  continuity.initialClaims = [];
  const run = exportRun(current, current.inputs, continuity);
  expect(run.framework).toBe('3.0.0');
  for (const exported of [run, compactRun(run)])
    expect(fingerprint(verifyImport(JSON.stringify(exported)).state)).toBe(fingerprint(current));
  expect(() => verifyImport(JSON.stringify({ ...run, framework: '2.18.0' }))).toThrow(/Start a new game/);
});

test('restoring a saved person preserves its narration choice', () => {
  const person = freshCast('nermin', 42, 510);
  person.lexicon = { plainEnglish: false, names: { nermin: 'Nermin' } };
  expect(restore(snapshot(person)).lexicon).toEqual(person.lexicon);
});

// Generated by the actual upgraded Voice4 producer from central978687c. No old snapshot was retagged.
test('admits an actual HF2.21 Voice departure with its source calendar and history intact', async () => {
  const parent = JSON.parse(
    readFileSync(new URL('./fixtures/voice4-hf221-departure.json', import.meta.url), 'utf8'),
  );
  expect(parent.source.engine).toBe('2.21.0');
  const admission = await prepareGuest(parent);
  expect(admission.history).toEqual(parent.transfer.history);
  expect(admission.calendar?.calendarHost.originSourceNow).toBe(2520);
  const current = newGame(7, 6, [admission]);
  while (current.now < admission.person.now)
    advance(current, Math.min(60, admission.person.now - current.now));
  // This source departs at18:00; the agency accepts Selin's first call after18:00.
  const arrivalDeadline = current.now + 60;
  while (
    current.now < arrivalDeadline &&
    view(current).guests?.find((g) => g.id === 'selin-voice')?.status !== 'available'
  )
    advance(current, 1);
  expect(view(current).guests?.find((g) => g.id === 'selin-voice')?.status).toBe('available');
  apply(current, { type: 'guest-action', guest: 'selin-voice', action: 'ask-service' });
  const end = current.now + 180;
  while (
    current.now < end &&
    view(current).guests?.find((g) => g.id === 'selin-voice')?.status !== 'complete'
  )
    advance(current, 1);
  expect(view(current).guests?.find((g) => g.id === 'selin-voice')?.status).toBe('complete');
  expect(current.people['selin-voice']?.lexicon?.plainEnglish).toBe(true);
  expect(fingerprint(replay(7, current.inputs, current.now, 6, [admission]))).toBe(fingerprint(current));
});

